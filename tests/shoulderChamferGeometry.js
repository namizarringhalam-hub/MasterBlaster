export function shoulderChamferGeometry() {
  const positions = new Float32Array(triangles.length * 3);
  triangles.forEach((vertex, i) => positions.set(vertices.slice(vertex * 3, vertex * 3 + 3), i * 3));
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute("position", new THREE.BufferAttribute(positions, 3));
  geometry.computeVertexNormals();
  const normal = geometry.attributes.normal, uv = new Float32Array(triangles.length * 2);
  for (let i = 0; i < triangles.length; i++) {
    const x = positions[i * 3], y = positions[i * 3 + 1], z = positions[i * 3 + 2];
    const cap = Math.abs(normal.getY(i)) > .99, radius = y > 0 ? .2 : .25;
    uv[i * 2] = cap ? x / (radius * 2) + .5 : (Math.atan2(x, z) / (Math.PI * 2) + 1) % 1;
    uv[i * 2 + 1] = cap ? z / (radius * 2) * Math.sign(y) + .5 : (y + .21) / .42;
  }
  for (let i = 0; i < triangles.length; i += 3) {
    if (Math.abs(normal.getY(i)) > .99) continue;
    const values = [uv[i * 2], uv[i * 2 + 2], uv[i * 2 + 4]];
    if (Math.max(...values) - Math.min(...values) > .5) for (let j = 0; j < 3; j++) if (values[j] < .5) uv[(i + j) * 2] += 1;
  }
  geometry.setAttribute("uv", new THREE.BufferAttribute(uv, 2));
  return geometry;
}

